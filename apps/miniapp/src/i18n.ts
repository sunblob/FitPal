const DICTS: Record<Language, Dict> = { ru, en };

/** Язык до загрузки профиля: из браузера, initTelegram уточняет его по данным Telegram. */
let current: Language = languageFromTelegram(navigator.language);

/**
 * Текущий словарь. Модульная переменная, а не контекст: при смене языка App
 * перемонтирует дерево (key={lang}), и все компоненты читают новый словарь.
 */
export let L: Dict = DICTS[current];

export function setLanguage(lang: Language) {
  current = lang;
  L = DICTS[lang];
  document.documentElement.lang = lang;
}

export const getLanguage = () => current;

/** Локаль для toLocaleDateString / toLocaleString. */
export const locale = () => LOCALES[current];

/** Число с разделителями разрядов по текущей локали. */
export const fmtNumber = (n: number) => n.toLocaleString(locale());
